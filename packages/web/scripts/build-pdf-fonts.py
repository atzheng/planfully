"""Builds the subset fonts in packages/web/public/fonts used by the PDF export.

Usage: python3 build-pdf-fonts.py <src dir> <out dir>
The src dir holds NotoSans-Regular/Bold.ttf, NotoSansThai-Regular/Bold.ttf and the variable
NotoSansJP.ttf, NotoSansSC.ttf and NotoSansKR.ttf (notofonts and google/fonts repos, all SIL OFL 1.1). Needs fonttools.
The output is committed; this script only documents how it was made.
"""
import sys
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

src, out = sys.argv[1], sys.argv[2]


def run(inp, outp, unicodes):
    opts = subset.Options()
    opts.layout_features = ["kern", "ccmp", "locl", "mark", "mkmk", "liga"]
    opts.hinting = False
    opts.notdef_outline = True
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    font = TTFont(inp) if isinstance(inp, str) else inp
    s = subset.Subsetter(opts)
    s.populate(unicodes=unicodes)
    s.subset(font)
    font.save(outp)


def rng(*pairs):
    out = set()
    for a, b in pairs:
        out.update(range(a, b + 1))
    return out


latin = rng((0x20, 0x7E), (0xA0, 0x24F), (0x1E00, 0x1EFF), (0x2000, 0x206F), (0x20A0, 0x20BF),
            (0x2100, 0x214F), (0x2190, 0x21FF), (0x2200, 0x22FF), (0x25A0, 0x25FF))
greek_cyr = rng((0x370, 0x3FF), (0x1F00, 0x1FFF), (0x400, 0x52F))
for w in ("Regular", "Bold"):
    run(f"{src}/NotoSans-{w}.ttf", f"{out}/NotoSans-{w}.ttf", latin | greek_cyr)
    run(f"{src}/NotoSansThai-{w}.ttf", f"{out}/NotoSansThai-{w}.ttf", latin | rng((0xE00, 0xE7F)))


def codec_chars(codec, rows):
    chars = set()
    for r in rows:
        for c in range(0xA1, 0xFF):
            try:
                chars.add(ord(bytes([r, c]).decode(codec)))
            except Exception:
                pass
    return chars


# Kana, CJK punctuation, fullwidth forms, Latin/Greek/Cyrillic, plus the kanji of JIS X 0208
# (levels 1 and 2) and the hanzi of GB 2312 (the font itself decides which of these it has: JP
# lacks simplified-only hanzi, SC lacks kana-era forms). Not full coverage: rare characters print as '?'.
cjk = rng((0x3000, 0x30FF), (0xFF00, 0xFFEF), (0x31F0, 0x31FF)) | latin | greek_cyr
cjk |= codec_chars("euc_jp", range(0xB0, 0xF5))
cjk |= codec_chars("gb2312", range(0xB0, 0xF8))
for name in ("JP", "SC"):
    vf = TTFont(f"{src}/NotoSans{name}.ttf")
    reg = instantiateVariableFont(vf, {"wght": 400})
    run(reg, f"{out}/NotoSans{name}-Regular.ttf", cjk)

# Korean: the 2,350 hangul syllables of KS X 1001 (covers everyday text, names and places; rare
# syllables print as '?'), compatibility jamo, CJK punctuation, fullwidth forms, Latin/Greek/Cyrillic.
# No hanja: Han text without hangul uses the SC/JP fonts.
kr = rng((0x3000, 0x303F), (0xFF00, 0xFFEF), (0x3130, 0x318F)) | latin | greek_cyr
kr |= codec_chars("euc_kr", range(0xB0, 0xC9))
vf = TTFont(f"{src}/NotoSansKR.ttf")
run(instantiateVariableFont(vf, {"wght": 400}), f"{out}/NotoSansKR-Regular.ttf", kr)


# Coverage of each output font as code point ranges, so the PDF code can print '?' for anything
# a font lacks instead of silently dropping it.
def ranges_of(path):
    cps = sorted(TTFont(path).getBestCmap().keys())
    res, start, prev = [], None, None
    for cp in cps:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            res.append((start, prev))
            start = prev = cp
    if start is not None:
        res.append((start, prev))
    return res


names = ["NotoSans-Regular", "NotoSans-Bold", "NotoSansThai-Regular", "NotoSansThai-Bold",
         "NotoSansJP-Regular", "NotoSansSC-Regular", "NotoSansKR-Regular"]
with open(sys.argv[3], "w") as f:
    f.write("// Generated by scripts/build-pdf-fonts.py: code point ranges present in each font file.\n")
    f.write("export const FONT_COVERAGE: Record<string, readonly (readonly [number, number])[]> = {\n")
    for name in names:
        pairs = ",".join(f"[{a},{b}]" for a, b in ranges_of(f"{out}/{name}.ttf"))
        f.write(f"  '{name}.ttf': [{pairs}],\n")
    f.write("};\n")
